def pii_type(suffix: str, label: bool) -> str:
    if not label:
        if suffix in TRUE_TYPE:
            raise SystemExit(f"{suffix} is negative but has a sensitive type")
        return "none"
    kind = TRUE_TYPE.get(suffix)
    if kind is None:
        raise SystemExit(f"{suffix} is positive but has no pii type")
    return kind


def main() -> None:
    if len(ROWS) != 100:
        raise SystemExit(f"expected 100 rows, got {len(ROWS)}")
    cases = []
    for suffix, style, tricky, label, reason, text in ROWS:
        cases.append({
            "id": f"pii-{suffix}",
            "style": style,
            "tricky": tricky,
            "contains_sensitive_pii": label,
            "pii_type": pii_type(suffix, label),
            "reason": reason,
            "text": text,
        })
    out = Path(__file__).with_name("prompts.json")
    out.write_text(json.dumps(cases, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(cases)} to {out}")

    mentions = [{
        "id": f"sm-{suffix}",
        "style": style,
        "tricky": tricky,
        "contains_sensitive_pii": label,
        "pii_type": "secret" if label else "none",
        "reason": reason,
        "text": text,
    } for suffix, style, tricky, label, reason, text in SECRET_MENTION_ROWS]
    if sum(m["contains_sensitive_pii"] for m in mentions) * 2 != len(mentions):
        raise SystemExit("secret mention set must be half sensitive")
    out = Path(__file__).with_name("secret_mentions.json")
    out.write_text(json.dumps(mentions, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(mentions)} to {out}")

    placeholders = [{
        "id": f"ph-{suffix}",
        "style": style,
        "tricky": tricky,
        "contains_sensitive_pii": kind != "none",
        "pii_type": kind,
        "reason": reason,
        "text": text,
    } for suffix, style, tricky, kind, reason, text in PLACEHOLDER_ROWS]
    if sum(p["contains_sensitive_pii"] for p in placeholders) * 2 != len(placeholders):
        raise SystemExit("placeholder set must be half sensitive")
    out = Path(__file__).with_name("placeholders.json")
    out.write_text(json.dumps(placeholders, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(placeholders)} to {out}")

    bare = [{
        "id": f"bn-{suffix}",
        "style": style,
        "tricky": tricky,
        "contains_sensitive_pii": kind != "none",
        "pii_type": kind,
        "reason": reason,
        "text": text,
    } for suffix, style, tricky, kind, reason, text in BARE_NUMBER_ROWS]
    if sum(b["contains_sensitive_pii"] for b in bare) * 2 != len(bare):
        raise SystemExit("bare number set must be half sensitive")
    out = Path(__file__).with_name("bare_numbers.json")
    out.write_text(json.dumps(bare, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(bare)} to {out}")


if __name__ == "__main__":
    main()
